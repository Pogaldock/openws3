#!/usr/bin/env python3
"""Turn tools/sprites.txt into src/sprites.c and src/sprites.h (1 bit per pixel, rows padded to bytes, MSB = leftmost).
   python3 tools/gen_sprites.py tools/sprites.txt src/sprites.c"""
import sys


def parse(path):
    sprites, name = [], None
    for line in open(path):
        line = line.rstrip('\n')
        if not line or line.startswith(';'):
            continue
        if line.startswith('= '):
            name = line[2:].strip()
            sprites.append((name, []))
        else:
            sprites[-1][1].append(line.strip())
    for name, rows in sprites:
        if len({len(r) for r in rows}) != 1:
            sys.exit('%s: rows have different widths' % name)
    return sprites


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    sprites = parse(sys.argv[1])
    out = sys.argv[2]
    bits, offs = [], []
    for name, rows in sprites:
        offs.append(len(bits))
        for r in rows:
            row = bytearray((len(r) + 7) // 8)
            for x, ch in enumerate(r):
                if ch == '#':
                    row[x // 8] |= 0x80 >> (x % 8)
            bits.extend(row)
    with open(out, 'w') as f:
        f.write('/* GENERATED by tools/gen_sprites.py from tools/sprites.txt - do not edit. */\n#include "sprites.h"\n\n')
        f.write('const CODE uint8_t spr_w[SPR_COUNT] = { %s };\n' % ', '.join(str(len(r[0])) for _, r in sprites))
        f.write('const CODE uint8_t spr_h[SPR_COUNT] = { %s };\n' % ', '.join(str(len(r)) for _, r in sprites))
        f.write('const CODE uint16_t spr_off[SPR_COUNT] = { %s };\n' % ', '.join(map(str, offs)))
        f.write('const CODE uint8_t spr_bits[%d] = {\n' % len(bits))
        for i in range(0, len(bits), 12):
            f.write('    ' + ', '.join('0x%02X' % b for b in bits[i:i + 12]) + ',\n')
        f.write('};\n')
    with open(out[:-2] + '.h', 'w') as f:
        f.write('/* GENERATED by tools/gen_sprites.py from tools/sprites.txt - do not edit. */\n')
        f.write('#ifndef SPRITES_H\n#define SPRITES_H\n#include "compat.h"\n')
        f.write('enum { %s, SPR_COUNT };\n' % ', '.join('SPR_' + n for n, _ in sprites))
        f.write('extern const CODE uint8_t spr_w[], spr_h[], spr_bits[];\nextern const CODE uint16_t spr_off[];\n')
        f.write('#define SPR_BITS(n) (spr_bits + spr_off[n])\n#endif\n')
    print('%s: %d sprites, %d bytes' % (out, len(sprites), len(bits)))


if __name__ == '__main__':
    main()
