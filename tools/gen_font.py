#!/usr/bin/env python3
"""tools/font5x7.txt -> src/font.c, and tools/font_rot.txt (the ROT theme's changed glyphs) -> src/font_rot.c
(column-major, 5 bytes per glyph, bit0 = top row).
Also importable: `glyphs()` returns {char: [7 strings]} for tests.   python3 tools/gen_font.py"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
FIRST, LAST = 0x20, 0x5A          # ' ' .. 'Z'


def glyphs(name='font5x7.txt', base=None):
    g, cur = dict(base) if base else {' ': ['.....'] * 7}, None
    for line in open(os.path.join(HERE, name)):
        line = line.rstrip('\n')
        if line.startswith(';') or not line.strip():
            continue
        if line.startswith('= '):
            cur = line[2]
            g[cur] = []
        else:
            assert len(line) == 5 and cur, line
            g[cur].append(line)
    for c, rows in g.items():
        assert len(rows) == 7, c
    return g


def write(g, array, src, dst):
    out = ['/* GENERATED by tools/gen_font.py from %s - do not edit. */' % src,
           '#include "font.h"', '',
           'const __code uint8_t %s[(FONT_LAST - FONT_FIRST + 1) * 5] = {' % array]
    for code in range(FIRST, LAST + 1):
        rows = g.get(chr(code))
        if rows is None:
            cols = [0] * 5
        else:
            cols = [sum((rows[r][c] == '#') << r for r in range(7)) for c in range(5)]
        out.append('    %s,  /* %s */' % (', '.join('0x%02X' % v for v in cols), repr(chr(code))))
    out.append('};')
    open(os.path.join(HERE, '..', 'src', dst), 'w').write('\n'.join(out) + '\n')
    print('wrote src/%s (%d glyphs defined)' % (dst, len(g)))


def main():
    g = glyphs()
    write(g, 'font5x7', 'tools/font5x7.txt', 'font.c')
    write(glyphs('font_rot.txt', g), 'font_rot', 'tools/font5x7.txt + tools/font_rot.txt', 'font_rot.c')


if __name__ == '__main__':
    main()
