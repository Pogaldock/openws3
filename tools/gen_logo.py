#!/usr/bin/env python3
"""Turn the SYMBIOZE wordmark (white on transparent PNG) into a 1-bit bitmap for the ROT splash.
   python3 tools/gen_logo.py tools/symbioze_logo.png src/logo.c [HEIGHT]
The output is one bit per pixel, rows top to bottom, each row padded to whole bytes, most significant bit = leftmost pixel.
Needs Pillow.  Only run when the logo changes: src/logo.c is committed, the firmware build does not need Python."""
import sys
from PIL import Image

THRESHOLD = 110        # 0..255 on the logo's coverage: lower keeps thinner strokes, higher cleans up the edges


def main():
    if len(sys.argv) not in (3, 4):
        sys.exit(__doc__)
    src, out = sys.argv[1:3]
    height = int(sys.argv[3]) if len(sys.argv) == 4 else 44

    im = Image.open(src).convert('RGBA')
    im = im.crop(im.getbbox())                                       # drop the empty margin round the wordmark
    width = max(8, round(im.width * height / im.height))
    width = min(width, 160)
    # coverage = alpha x brightness: the wordmark is white where it is drawn and transparent elsewhere
    r, g, b, a = im.split()
    cover = Image.composite(Image.merge('RGB', (r, g, b)).convert('L'), Image.new('L', im.size, 0), a)
    cover = cover.resize((width, height), Image.LANCZOS)

    stride = (width + 7) // 8
    rows = []
    for y in range(height):
        row = bytearray(stride)
        for x in range(width):
            if cover.getpixel((x, y)) >= THRESHOLD:
                row[x // 8] |= 0x80 >> (x % 8)
        rows.append(row)

    with open(out, 'w') as f:
        f.write('/* GENERATED by tools/gen_logo.py from tools/symbioze_logo.png - do not edit. */\n')
        f.write('#include "logo.h"\n\n')
        f.write('/* %d x %d, %d bytes per row; "#" = lit in the comment after each row */\n' % (width, height, stride))
        f.write('const CODE uint8_t logo_bits[LOGO_H * LOGO_STRIDE] = {\n')
        for row in rows:
            art = ''.join('#' if row[x // 8] & (0x80 >> (x % 8)) else '.' for x in range(width))
            f.write('    ' + ', '.join('0x%02X' % v for v in row) + ',  /* ' + art + ' */\n')
        f.write('};\n')

    with open(out[:-2] + '.h', 'w') as f:
        f.write('/* GENERATED by tools/gen_logo.py - do not edit.  The SYMBIOZE wordmark for the ROT splash, 1 bit per pixel. */\n')
        f.write('#ifndef SYMBIOZE_LOGO_H\n#define SYMBIOZE_LOGO_H\n#include "compat.h"\n')
        f.write('#define LOGO_W      %d\n#define LOGO_H      %d\n#define LOGO_STRIDE %d\n' % (width, height, stride))
        f.write('extern const CODE uint8_t logo_bits[];\n#endif\n')
    print('%s: %d x %d, %d bytes' % (out, width, height, stride * height))


if __name__ == '__main__':
    main()
